// Generates src/api/generated/<service>.ts from contracts/openapi/<service>.yaml with
// openapi-typescript. The output is committed, because the frontend image is built with
// ./frontend as Docker context and cannot see ../contracts.
//
//   npm run generate:api   regenerate after a contract change
//   npm run check:api      fail if the committed files differ from the contracts
import { mkdir, readFile, readdir, writeFile } from 'node:fs/promises';
import { dirname, join, basename } from 'node:path';
import { fileURLToPath } from 'node:url';
import openapiTS, { astToString } from 'openapi-typescript';

const frontendDir = join(dirname(fileURLToPath(import.meta.url)), '..');
const contractsDir = join(frontendDir, '..', 'contracts', 'openapi');
const outDir = join(frontendDir, 'src', 'api', 'generated');
const check = process.argv.includes('--check');

const HEADER = `/**
 * This file was auto-generated by openapi-typescript.
 * Do not make direct changes to the file.
 */

`;

const specs = (await readdir(contractsDir)).filter((f) => f.endsWith('.yaml')).sort();
await mkdir(outDir, { recursive: true });

const stale = [];
for (const spec of specs) {
  const service = basename(spec, '.yaml');
  const ast = await openapiTS(new URL(`file://${join(contractsDir, spec)}`));
  const output = HEADER + astToString(ast);
  const target = join(outDir, `${service}.ts`);

  if (check) {
    const current = await readFile(target, 'utf8').catch(() => null);
    if (current !== output) stale.push(`src/api/generated/${service}.ts`);
  } else {
    await writeFile(target, output);
    console.log(`contracts/openapi/${spec} -> src/api/generated/${service}.ts`);
  }
}

if (stale.length > 0) {
  console.error(`Generated API types are out of date: ${stale.join(', ')}. Run: npm run generate:api`);
  process.exit(1);
}
if (check) console.log(`Generated API types match ${specs.length} contracts.`);
