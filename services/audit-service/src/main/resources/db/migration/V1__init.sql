-- append-only log of every business event. The service only inserts and reads; there is no UPDATE or DELETE
-- endpoint and no code path that modifies a row (the audit trail itself must be immutable).
CREATE TABLE audit_entry (
    audit_id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- Unique: a redelivered event is appended once. This is the idempotency key of the consumer.
    event_id          UUID NOT NULL UNIQUE,
    event_type        VARCHAR(120) NOT NULL,
    occurred_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    producer          VARCHAR(60) NOT NULL,
    aggregate_id      BIGINT,
    aggregate_version BIGINT,
    correlation_id    VARCHAR(128),
    received_at       TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    -- The original body, stored unchanged (schema AuditEntry.envelope).
    envelope          JSONB NOT NULL
);
CREATE INDEX ix_audit_entry_type_time ON audit_entry (event_type, occurred_at DESC);
CREATE INDEX ix_audit_entry_aggregate ON audit_entry (aggregate_id);
CREATE INDEX ix_audit_entry_correlation ON audit_entry (correlation_id);
CREATE INDEX ix_audit_entry_received ON audit_entry (received_at DESC);
