-- notification-service owns in-app notifications and the employee contact replica it needs to address emails.
-- One migration because the service is new; later changes get V2, V3, ... (forward-only).

-- Idempotent consumer: an eventId is stored in the same transaction as its notifications.
CREATE TABLE processed_event (
    event_id UUID PRIMARY KEY
);

-- Local copy of the employee fields notification-service needs (email, role, active).
-- Built from workforce.employee.* events; highest aggregate_version wins and a tombstone cannot be resurrected.
CREATE TABLE employee_contact (
    employee_id       BIGINT PRIMARY KEY,
    email             VARCHAR(320) NOT NULL,
    user_role         VARCHAR(20) NOT NULL,
    employment_status VARCHAR(30) NOT NULL,
    aggregate_version BIGINT NOT NULL,
    deleted           BOOLEAN NOT NULL DEFAULT FALSE
);

-- In-app notifications (contracts/openapi/notification.yaml, schema Notification).
-- is_read is named like that because READ is a SQL keyword in some engines; the API field is "read".
CREATE TABLE notification (
    notification_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id       BIGINT NOT NULL,
    title             VARCHAR(200) NOT NULL,
    message           TEXT,
    source_event_type VARCHAR(120) NOT NULL,
    source_event_id   UUID NOT NULL REFERENCES processed_event(event_id),
    created_at        TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    is_read           BOOLEAN NOT NULL DEFAULT FALSE,
    -- One notification per event and recipient: a redelivery cannot duplicate it even before processed_event is read.
    CONSTRAINT uq_notification_event_employee UNIQUE (source_event_id, employee_id)
);
CREATE INDEX ix_notification_employee ON notification (employee_id, is_read, created_at DESC);

-- Transactional outbox: notification.email.requested.v1 is committed with the notification it belongs to.
CREATE TABLE outbox_event (
    event_id     UUID PRIMARY KEY,
    event_type   VARCHAR(120) NOT NULL,
    payload      TEXT NOT NULL,
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    published_at TIMESTAMP WITH TIME ZONE
);
CREATE INDEX ix_outbox_unpublished ON outbox_event (created_at) WHERE published_at IS NULL;
